window.CATEGORY_EN = { 'AI & Automazione': 'AI & Automation', 'Business': 'Business', 'Esperienze': 'Experiences', 'Vita quotidiana': 'Everyday life' };

(function () {
  let lang = 'it';
  try { lang = localStorage.getItem('mb3d-language') === 'en' ? 'en' : 'it'; } catch (e) {}
  try { const q = new URLSearchParams(location.search).get('lang'); if (q === 'en' || q === 'it') { lang = q; localStorage.setItem('mb3d-language', q); } } catch (e) {}
  window.getLang = () => lang;
  window.t = (key) => (window.I18N[key] ? window.I18N[key][lang] : key);
  window.catLabel = (c) => (lang === 'en' ? (window.CATEGORY_EN[c] || c) : c);

  window.applyLanguage = function (next) {
    if (next) { lang = next; try { localStorage.setItem('mb3d-language', lang); } catch (e) {} }
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
    document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
    document.querySelectorAll('[data-i18n-alt]').forEach(el => { el.alt = t(el.dataset.i18nAlt); });
    document.title = t('js.title');
    document.querySelector('meta[name="description"]').content = t('js.desc');
    document.querySelector('#close').setAttribute('aria-label', t('js.close'));
    document.querySelector('.filters').setAttribute('aria-label', t('js.filter'));
    document.querySelector('#project-index').setAttribute('aria-label', t('js.list'));
    document.querySelector('#orbit-prev').setAttribute('aria-label', t('js.prev'));
    document.querySelector('#orbit-next').setAttribute('aria-label', t('js.next'));
    document.querySelector('#music-toggle').setAttribute('aria-label', t('js.music'));
    document.querySelectorAll('[data-lang]').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
    document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  };
  window.applyLanguage();
})();
